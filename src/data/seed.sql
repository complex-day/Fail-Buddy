-- Fail Buddy — Supabase Schema & Seed Script
-- Run in Supabase SQL Editor (safe to execute multiple times).

-- 1. Tables
create table if not exists public.subjects (
  code text primary key,
  name text not null,
  branch text not null,
  semester integer not null,
  exam_date date not null,
  passing_target text not null,
  topper_name text not null,
  unlocked_by text[] not null default '{}'::text[]
);

create table if not exists public.materials (
  id bigint generated by default as identity primary key,
  subject_code text not null references public.subjects(code) on delete cascade,
  type text not null check (type in ('IMP', 'ASSIGNMENT')),
  unit integer not null,
  question text not null,
  answer text not null,
  proof_tag text not null,
  topper_tip text,
  is_must_do boolean not null default true,
  is_locked boolean not null default false
);

create table if not exists public.contributions (
  id bigint generated by default as identity primary key,
  student_name text not null,
  subject_code text not null,
  resource_type text not null check (resource_type in ('MID_PAPER', 'ASSIGNMENT', 'NOTES')),
  resource_link_or_note text not null,
  created_at timestamptz not null default now()
);

-- 2. Row Level Security (RLS)
alter table public.subjects enable row level security;
alter table public.materials enable row level security;
alter table public.contributions enable row level security;

drop policy if exists "Allow anon select on subjects" on public.subjects;
create policy "Allow anon select on subjects"
  on public.subjects
  for select
  to anon
  using (true);

drop policy if exists "Allow anon select on materials" on public.materials;
create policy "Allow anon select on materials"
  on public.materials
  for select
  to anon
  using (true);

drop policy if exists "Allow anon insert on contributions" on public.contributions;
create policy "Allow anon insert on contributions"
  on public.contributions
  for insert
  to anon
  with check (true);

